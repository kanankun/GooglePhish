#!/usr/bin/env bash
#
# deploy.sh - bring the Week 1 phishing-simulation stack up on a server.
#
# Safe to run more than once: it only fills in what is missing. It does not
# overwrite an .env you have already edited.
#
#   ./deploy.sh                 interactive - asks for the values it needs
#   PUBLIC_HOST=phish.example.com C2_PASSWORD=s3cret ./deploy.sh   non-interactive
#
# Environment variables it reads (all optional; prompts fill the gaps):
#   PUBLIC_HOST   domain or IP people will type           (default: localhost)
#   C2_PASSWORD   console password                         (default: asked)
#   PROFILE       https | http                             (default: https)
#   BRAND         name shown on the console                (default: evilucimx)
#   BIND          0.0.0.0 to accept outside connections    (default: 0.0.0.0)

set -euo pipefail

cd "$(dirname "$0")"

say()  { printf '\033[1;36m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mxx\033[0m %s\n' "$*" >&2; exit 1; }

# --- 1. Docker + compose --------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
    warn "Docker is not installed."
    if [ "$(uname -s)" = "Linux" ]; then
        read -r -p "Install it now with get.docker.com? [y/N] " ans
        case "$ans" in
            [yY]*) curl -fsSL https://get.docker.com | sh ;;
            *) die "Install Docker, then re-run this script." ;;
        esac
    else
        die "Install Docker Desktop (https://www.docker.com/products/docker-desktop/) and start it, then re-run."
    fi
fi

if docker compose version >/dev/null 2>&1; then
    COMPOSE="docker compose"
elif command -v docker-compose >/dev/null 2>&1; then
    COMPOSE="docker-compose"
else
    die "docker compose is not available. Install the Compose plugin and re-run."
fi

docker info >/dev/null 2>&1 || die "Docker is installed but not running. Start it and re-run."

# --- 2. .env --------------------------------------------------------------
gen_key() {
    python3 -c "import secrets,string; print(''.join(secrets.choice(string.ascii_letters+string.digits+'!@#\$%^&*(-_=+)') for _ in range(50)))" 2>/dev/null \
        || head -c 50 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 50
}

if [ ! -f .env ]; then
    say "No .env found - creating one."

    PUBLIC_HOST="${PUBLIC_HOST:-}"
    if [ -z "$PUBLIC_HOST" ]; then
        read -r -p "Domain or IP people will open (PUBLIC_HOST) [localhost]: " PUBLIC_HOST
        PUBLIC_HOST="${PUBLIC_HOST:-localhost}"
    fi

    C2_PASSWORD="${C2_PASSWORD:-}"
    if [ -z "$C2_PASSWORD" ]; then
        read -r -s -p "Console password (C2_PASSWORD): " C2_PASSWORD; echo
        [ -n "$C2_PASSWORD" ] || die "A console password is required."
    fi

    PROFILE="${PROFILE:-https}"
    BRAND="${BRAND:-evilucimx}"
    BIND="${BIND:-0.0.0.0}"

    # HTTPS flag mirrors the profile: 1 only when Caddy terminates TLS.
    if [ "$PROFILE" = "https" ]; then HTTPS=1; else HTTPS=0; fi

    SECRET_KEY="$(gen_key)"

    umask 077
    cat > .env <<EOF
# Generated by deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
DJANGO_SECRET_KEY=${SECRET_KEY}
C2_PASSWORD=${C2_PASSWORD}
BIND=${BIND}
PUBLIC_HOST=${PUBLIC_HOST}
HTTPS=${HTTPS}
COMPOSE_PROFILES=${PROFILE}
BRAND=${BRAND}
EOF
    say ".env written (permissions 600)."
else
    say ".env already exists - leaving it as is."
    if grep -q '^C2_PASSWORD=admin$' .env; then
        warn "C2_PASSWORD is still 'admin' in .env - change it before using this for real."
    fi
    if grep -q '^DJANGO_SECRET_KEY=lF%' .env; then
        warn "DJANGO_SECRET_KEY looks like the example default - generate a fresh one."
    fi
fi

# --- 3. Build and launch --------------------------------------------------
say "Building and starting the stack..."
$COMPOSE up -d --build

echo
say "Status:"
$COMPOSE ps

# --- 4. Where things are --------------------------------------------------
PUBLIC_HOST="$(grep -E '^PUBLIC_HOST=' .env | cut -d= -f2-)"
PROFILE="$(grep -E '^COMPOSE_PROFILES=' .env | cut -d= -f2-)"
SCHEME="https"; [ "$PROFILE" = "http" ] && SCHEME="http"

echo
say "Phishing page:  ${SCHEME}://${PUBLIC_HOST}"
[ "$PROFILE" = "https" ] && echo "    (self-signed cert - the browser warning is expected; click through)"
echo
say "Console (data):  no port published anywhere. From your laptop run:"
echo "    ./console.sh <user>@<this-server>"
echo "    then open http://localhost:8001/gate"
echo
say "Logs:  $COMPOSE logs -f      Stop:  $COMPOSE down"

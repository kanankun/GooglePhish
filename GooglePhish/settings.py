# Both of these are needed, always.
#
# STATICFILES_DIRS is where the project's own assets live; STATIC_ROOT is
# where collectstatic gathers them for serving. They only conflict if
# STATIC_ROOT sits *inside* STATICFILES_DIRS, and 'static' and
# 'serve_static' are siblings.
#
# Defining STATICFILES_DIRS only under DEBUG meant that in production
# collectstatic had no source directory and gathered nothing but the admin
# theme - so styles.css, script.js and visit.js all 404'd and the landing
# page rendered with no styling at all.
STATICFILES_DIRS = [os.path.join(BASE_DIR, 'static')]
STATIC_ROOT = os.path.join(BASE_DIR, 'serve_static')

# TLS is terminated by the reverse proxy in front, so request.is_secure()
# would otherwise be False and Django would compare an http:// origin
# against the https:// entries in CSRF_TRUSTED_ORIGINS and reject every
# POST. The proxy tells us the real scheme in this header.
#
# Only safe because the containers are bound to loopback and the proxy is
# the only route in - exposed directly, a client could simply claim https.
SECURE_PROXY_SSL_HEADER = ('HTTP_X_FORWARDED_PROTO', 'https')
USE_X_FORWARDED_HOST = True

## accept CSRF tokens from different domains
CSRF_TRUSTED_ORIGINS = CSRF_TRUSTED_ORIGINS_VARIABLE

# VULN-7 fix: cookie security flags
# A Secure cookie is only ever sent over HTTPS. Tying that to DEBUG was
# wrong: with DEBUG off but no TLS - which is exactly how you run it on a
# LAN to show somebody - the browser holds the CSRF cookie back and every
# form submission is rejected with 403. The page loads fine, so it looks
# like the form is broken rather than the cookie.
#
# Tie it to whether there is actually HTTPS in front instead. Caddy sets
# HTTPS=1 on the droplet; on a LAN you leave it unset.
SECURE_COOKIES = environ.get('HTTPS', '') == '1'
CSRF_COOKIE_SECURE = SECURE_COOKIES
SESSION_COOKIE_SECURE = SECURE_COOKIES
CSRF_COOKIE_HTTPONLY = True       # prevent JS from reading CSRF cookie
SESSION_COOKIE_HTTPONLY = True    # prevent JS from reading session cookie
SESSION_COOKIE_SAMESITE = 'Lax'   # CSRF mitigation for cross-site requests